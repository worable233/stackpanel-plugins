/**
 * Inline the vendored widget into a TypeScript module.
 *
 * Plugins run in an isolated worker with no filesystem access, so the script has
 * to travel inside the bundle. Generating the module (instead of importing a
 * `.js` asset) keeps the bundler honest: the file is a plain string, and a
 * missing or emptied asset fails the build here rather than at runtime with a
 * blank widget.
 */
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const asset = path.join(root, 'assets', 'altcha.min.js');
const target = path.join(root, 'src', 'widget-asset.ts');

const source = readFileSync(asset, 'utf8');
if (source.trim().length < 10_000) {
  throw new Error(`[embed-widget] ${asset} looks empty (${source.length} bytes) — refusing to embed`);
}
const digest = createHash('sha256').update(source).digest('hex');

// `JSON.stringify` produces a valid TS string literal (escapes quotes, and the
// minified script contains no `</script>`-sensitive sequences for a JS module).
const contents = `// Generated by scripts/embed-widget.mjs — do not edit.
//
// Vendored ALTCHA widget, served by \`GET /altcha/widget.js\` and loaded by the
// host from the same origin (via the kernel BFF), so no CSP source is needed.
// Provenance and the upgrade procedure are in \`assets/NOTICE.md\`.

/** sha256 of the embedded script, for support and cache-busting. */
export const WIDGET_HASH = '${digest}';

/** The widget source is typed as a string in the generated .d.ts. */
export const WIDGET_SCRIPT: string = ${JSON.stringify(source)};
`;

const previous = (() => {
  try {
    return readFileSync(target, 'utf8');
  } catch {
    return '';
  }
})();
if (previous !== contents) writeFileSync(target, contents);
console.log(
  `[embed-widget] ${path.relative(root, target)} <- assets/altcha.min.js (${statSync(asset).size} bytes, sha256 ${digest.slice(0, 12)})`,
);
